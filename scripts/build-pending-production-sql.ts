/**
 * Generates server/migrations/pending_production.sql: everything production needs to match
 * the current schema, in order, in one transaction. Every statement is idempotent.
 *   npx tsx scripts/build-pending-production-sql.ts
 * Production is migrated by hand from this file; scripts never connect to production.
 */
import fs from 'fs';
import path from 'path';

const root = process.cwd();
const parts = [
  ['server/schema.sql', fs.readFileSync(path.join(root, 'server', 'schema.sql'), 'utf8')],
  [
    'server/migrations/attempts_metadata_backfill.sql',
    fs.readFileSync(path.join(root, 'server', 'migrations', 'attempts_metadata_backfill.sql'), 'utf8'),
  ],
];

const body = parts
  .map(([name, sql]) => `-- ════ BEGIN ${name} ════\n${sql.trim()}\n-- ════ END ${name} ════`)
  .join('\n\n');

const out = `-- pending_production.sql — GENERATED by scripts/build-pending-production-sql.ts. Do not edit by hand.
-- Brings any earlier production schema up to the current schema. Idempotent: safe to run repeatedly.
-- Apply with:  psql "$PRODUCTION_DATABASE_URL" -v ON_ERROR_STOP=1 -f server/migrations/pending_production.sql
BEGIN;

${body}

COMMIT;
`;

const target = path.join(root, 'server', 'migrations', 'pending_production.sql');
fs.writeFileSync(target, out, 'utf8');
console.log(`Wrote ${target}`);
